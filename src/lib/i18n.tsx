const DICTS: Record<Lang, Dict> = { en, hi, bn };

interface Ctx {
  lang: Lang;
  display: string;
  setDisplay: (d: string) => void;
  t: (key: string) => string;
}

const LangContext = createContext<Ctx | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [display, setDisplay] = useState<string>(
    () => localStorage.getItem("vyaparsathi.lang") || "English",
  );
  const lang = langCode(display);
  const setDisplayPersist = (d: string) => {
    setDisplay(d);
    localStorage.setItem("vyaparsathi.lang", d);
  };
  const t = (key: string) => DICTS[lang][key] ?? en[key] ?? key;
  return (
    <LangContext.Provider value={{ lang, display, setDisplay: setDisplayPersist, t }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang must be used within LanguageProvider");
  return ctx;
}
